-- Sinau: skema inti (mengikuti data di sinau-prototipe.html)

-- ============ Profil pengguna ============
create table public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  name        text not null check (char_length(name) between 3 and 40),
  email       text not null,
  angkatan    smallint check (angkatan between 2015 and 2100),
  role        text not null default 'user' check (role in ('user','admin')),
  avatar_url  text,
  reminder    boolean not null default true,
  active      boolean not null default true,
  streak      integer not null default 0 check (streak >= 0),
  last_active date,
  created_at  timestamptz not null default now()
);
comment on table public.profiles is 'Satu baris per akun. role diatur admin, bukan oleh pengguna sendiri.';

-- ============ Materi ============
create table public.languages (
  id          text primary key,                -- 'python', 'java'
  name        text not null,
  mono        text not null,
  color       text not null,
  accent      text not null,
  description text,
  position    smallint not null default 0,
  created_at  timestamptz not null default now()
);

create table public.units (                     -- tampil sebagai "Tugas 1..4"
  id          bigint generated by default as identity primary key,
  language_id text not null references public.languages(id) on delete cascade,
  title       text not null check (char_length(title) >= 3),
  position    smallint not null default 0,
  created_at  timestamptz not null default now(),
  unique (language_id, title)
);
create index units_language_idx on public.units(language_id, position);

create table public.lessons (                   -- "pembahasan"
  id           bigint generated by default as identity primary key,
  unit_id      bigint not null references public.units(id) on delete cascade,
  title        text not null check (char_length(title) >= 3),
  type         text not null default 'mc' check (type in ('mc','order','result','mix')),
  duration_min smallint not null default 5 check (duration_min > 0),
  xp           smallint not null default 15 check (xp >= 0),
  published    boolean not null default false,
  position     smallint not null default 0,
  material     jsonb not null default '{}'::jsonb,  -- {intro, points:[[judul,isi]], code, tip}
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index lessons_unit_idx on public.lessons(unit_id, position);

create table public.questions (                 -- soal tugas tiap pembahasan
  id          bigint generated by default as identity primary key,
  lesson_id   bigint not null references public.lessons(id) on delete cascade,
  position    smallint not null default 0,
  type        text not null check (type in ('mc','order','result')),
  prompt      text not null,
  options     jsonb not null default '[]'::jsonb, -- pilihan / blok kode / tabel hasil
  answer      jsonb not null,                     -- indeks jawaban atau urutan benar
  explanation text
);
create index questions_lesson_idx on public.questions(lesson_id, position);

-- ============ Progres & nilai ============
create table public.lesson_progress (
  user_id       uuid not null references public.profiles(id) on delete cascade,
  lesson_id     bigint not null references public.lessons(id) on delete cascade,
  passed        boolean not null default false,
  correct       smallint not null default 0,
  total         smallint not null default 0,
  attempts      smallint not null default 0,
  failed_before boolean not null default false,  -- pernah gagal → dihitung "kesusahan" di dasbor
  xp_earned     smallint not null default 0,
  completed_at  timestamptz,
  updated_at    timestamptz not null default now(),
  primary key (user_id, lesson_id)
);
create index lesson_progress_lesson_idx on public.lesson_progress(lesson_id);

create table public.reminders (                  -- tab Informasi: deadline tugas & pengingat kelas
  id          bigint generated by default as identity primary key,
  type        text not null check (type in ('deadline','kelas')),
  lesson_id   bigint references public.lessons(id) on delete cascade,
  due_date    date,
  course      text,
  class_date  date,
  start_time  time,
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now(),
  check ( (type = 'deadline' and lesson_id is not null and due_date is not null)
       or (type = 'kelas' and course is not null and class_date is not null and start_time is not null) )
);
create index reminders_lesson_idx on public.reminders(lesson_id);
create index reminders_created_by_idx on public.reminders(created_by);

create table public.submissions (                -- pengumpulan tugas (telat → menunggu persetujuan)
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references public.profiles(id) on delete cascade,
  lesson_id    bigint not null references public.lessons(id) on delete cascade,
  correct      smallint not null check (correct >= 0),
  total        smallint not null check (total > 0 and correct <= total),
  late_days    smallint not null default 0 check (late_days >= 0),
  status       text not null default 'ontime' check (status in ('ontime','pending','approved','rejected')),
  submitted_at timestamptz not null default now(),
  decided_at   timestamptz,
  decided_by   uuid references public.profiles(id) on delete set null
);
create index submissions_user_idx on public.submissions(user_id);
create index submissions_lesson_idx on public.submissions(lesson_id);
create index submissions_decided_by_idx on public.submissions(decided_by);

-- ============ Informasi & masukan ============
create table public.posts (
  id          bigint generated by default as identity primary key,
  category    text not null check (category in ('tentang','update','umum')),
  title       text not null check (char_length(title) >= 3),
  body        text not null,
  pinned      boolean not null default false,
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);
create index posts_created_by_idx on public.posts(created_by);

create table public.post_reads (
  user_id uuid not null references public.profiles(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  read_at timestamptz not null default now(),
  primary key (user_id, post_id)
);
create index post_reads_post_idx on public.post_reads(post_id);

create table public.feedback (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles(id) on delete cascade,
  type        text not null check (type in ('saran','error','soal')),
  text        text not null check (char_length(text) between 5 and 1000),
  context     jsonb not null default '{}'::jsonb,
  status      text not null default 'baru' check (status in ('baru','proses','selesai')),
  created_at  timestamptz not null default now()
);
create index feedback_user_idx on public.feedback(user_id);
